# Utility Apps' JSON calls ask for structured output (OpenAI-compatible `response_format`,
# Anthropic `output_config.format`), fall back without it when a server refuses it, and say
# so plainly when an answer was cut off at the model's limit.
#  1. Stops a running dev app.  2. Every check (check.ps1).
#  3. Commits the changed files by name with logs\commit-msg-structured-output.txt when green.
#  4. Starts the app for the manual check (an SP Page Builder addon with Gemma in LM Studio).
. "$PSScriptRoot\_common.ps1"
Get-Process -Name oxide, oxide-mcp-mock -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
Get-NetTCPConnection -LocalPort 1420 -State Listen -ErrorAction SilentlyContinue |
  ForEach-Object { Stop-Process -Id $_.OwningProcess -Force -ErrorAction SilentlyContinue }

& "$PSScriptRoot\check.ps1"
$checks = $LASTEXITCODE

$msg = Join-Path $Root 'logs\commit-msg-structured-output.txt'
$paths = @(
  'PROGRESS.md',
  'crates/oxide-llm/src/types.rs', 'crates/oxide-llm/src/openai.rs', 'crates/oxide-llm/src/anthropic.rs',
  'crates/oxide-agent/src/apps/runtime.rs', 'crates/oxide-agent/src/apps/tests.rs',
  'src-tauri/permissions/autogenerated/choose_app_folder.toml',
  'src-tauri/permissions/autogenerated/clear_app_folder.toml',
  'scripts/win/structured-output.cmd', 'scripts/win/structured-output.ps1'
)
if ($checks -eq 0 -and (Test-Path $msg)) {
  Start-Log 'commit'
  Run 'git add' ("git add -- " + ($paths -join ' '))
  Run 'git commit' "git commit -F `"$msg`""
  Run 'git log' 'git log --oneline -n 3'
  Run 'git status' 'git status --short'
  End-Log
  Write-Host 'All green and committed. Starting Oxide (close its window when done).' -ForegroundColor Green
} else {
  Write-Host 'Something failed: see logs\check-summary.log. Not committed. Starting Oxide anyway.' -ForegroundColor Red
}
Start-Process -FilePath (Join-Path $PSScriptRoot 'dev.cmd')
