/// Writes the TypeScript bindings for all registered commands and events.
pub fn export_bindings() -> anyhow::Result<()> {
    specta_builder().export(
        specta_typescript::Typescript::default()
            .header(BINDINGS_HEADER)
            // Timestamps are i64 milliseconds: well inside JS's safe integer range.
            .bigint(BigIntExportBehavior::Number),
        BINDINGS_PATH,
    )?;
    Ok(())
}

/// Registers the `oxide://` scheme (Windows and Linux; macOS takes it from the bundle) and
/// handles links: the one Oxide was started with and any that arrive while it runs.
fn setup_deep_links(app: &tauri::AppHandle) {
    use tauri_plugin_deep_link::DeepLinkExt as _;
    let links = app.deep_link();
    #[cfg(any(windows, target_os = "linux"))]
    if let Err(e) = links.register(oxide_core::desktop::DEEP_LINK_SCHEME) {
        tracing::warn!("couldn't register oxide:// links: {e}");
    }
    let handle = app.clone();
    links.on_open_url(move |event| {
        for url in event.urls() {
            desktop::open_url(&handle, url.as_str());
        }
    });
    match links.get_current() {
        Ok(Some(urls)) => {
            for url in urls {
                desktop::open_url(app, url.as_str());
            }
        }
        Ok(None) => {}
        Err(e) => tracing::debug!("start-up link: {e}"),
    }
}

fn init_tracing() {
    let filter = EnvFilter::try_from_default_env()
        .unwrap_or_else(|_| EnvFilter::new("info,oxide=debug,oxide_lib=debug"));
    // Ignore the error if a subscriber is already set (e.g. in tests).
    let _ = tracing_subscriber::fmt().with_env_filter(filter).try_init();
}

/// Starts the Oxide desktop app.
pub fn run() -> anyhow::Result<()> {
    init_tracing();

    // Keep the bindings in sync on every debug run.
    #[cfg(debug_assertions)]
    if let Err(err) = export_bindings() {
        tracing::warn!("could not export TypeScript bindings: {err:#}");
    }

    let builder = specta_builder();
    // Started at login: stay in the tray.
    let start_hidden = std::env::args().any(|a| a == desktop::HIDDEN_ARG);

    let app = tauri::Builder::default()
        // First, so a second launch hands its arguments (a deep link) over and exits.
        .plugin(tauri_plugin_single_instance::init(|app, args, _cwd| {
            match oxide_core::desktop::deep_link_in_args(&args) {
                Some(action) => desktop::dispatch(app, action),
                None => desktop::show_main(app),
            }
        }))
        .plugin(tauri_plugin_deep_link::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(
            tauri_plugin_autostart::Builder::new()
                .args([desktop::HIDDEN_ARG])
                .build(),
        )
        .plugin(
            tauri_plugin_global_shortcut::Builder::new()
                .with_handler(desktop::shortcut::handle)
                .build(),
        )
        .plugin(
            tauri_plugin_window_state::Builder::new()
                .with_state_flags(desktop::window_state_flags())
                .with_denylist(&[desktop::quick::QUICK_LABEL])
                .build(),
        )
        .on_window_event(desktop::on_window_event)
        // The sandboxed frame for HTML and React artifacts (see artifact_frame.rs).
        .register_asynchronous_uri_scheme_protocol(
            artifact_frame::SCHEME,
            |ctx, request, responder| {
                let app = ctx.app_handle().clone();
                let path = request
                    .uri()
                    .path_and_query()
                    .map(|p| p.as_str().to_owned())
                    .unwrap_or_else(|| "/".into());
                tauri::async_runtime::spawn(async move {
                    responder.respond(artifact_frame::respond(app, path).await);
                });
            },
        )
        .invoke_handler(builder.invoke_handler());

    #[cfg(target_os = "macos")]
    let app = app
        .menu(desktop::menu::build)
        .on_menu_event(desktop::menu::on_menu_event);

    let app = app
        .setup(move |app| {
            builder.mount_events(app);
            app.manage(desktop::DesktopState::default());
            let dirs = state::AppDirs {
                data: app.path().app_data_dir()?,
                config: app.path().app_config_dir()?,
                logs: app.path().app_log_dir()?,
            };
            let service = app.config().identifier.clone();
            let sink = Arc::new(events::TauriSink::new(app.handle().clone()));
            let handle = app.handle().clone();
            let state = tauri::async_runtime::block_on(state::AppState::open(
                &dirs,
                &service,
                sink,
                Arc::new(events::TauriPythonSink::new(app.handle().clone())),
                Arc::new(events::TauriSandboxSink::new(app.handle().clone())),
                Arc::new(events::TauriBrowserSink::new(app.handle().clone())),
                Arc::new(events::TauriChromeSink::new(app.handle().clone())),
                Arc::new(events::TauriScheduleSink::new(app.handle().clone())),
                move |models, secrets| state::McpParts {
                    sink: Arc::new(mcp_bridge::TauriMcpSink::new(handle.clone())),
                    agent: Arc::new(mcp_bridge::AppAgent::new(handle.clone(), models.clone())),
                    tokens: Arc::new(mcp_bridge::KeychainTokens::new(secrets.clone())),
                },
            ))?;
            let mcp = state.mcp.clone();
            let extensions = state.extensions.clone();
            let sandboxes = state.sandboxes.clone();
            let browser = state.browser.clone();
            let scheduler = state.scheduler.clone();
            let settings = tauri::async_runtime::block_on(state.store.app_settings())
                .unwrap_or_else(|e| {
                    tracing::warn!("settings: {e}");
                    oxide_core::AppSettings::default()
                });
            app.manage(state);
            // Servers start in the background; the window doesn't wait for them.
            tauri::async_runtime::spawn(async move {
                if let Err(e) = mcp.start().await {
                    tracing::warn!("MCP config: {e}");
                }
                // Then the installed extensions' servers.
                extensions.refresh().await;
            });
            // Idle sandboxes stop after a while (and ones an earlier run left running).
            tauri::async_runtime::spawn(async move { sandboxes.start_reaper() });
            // Chats' browsers close after a while without use.
            tauri::async_runtime::spawn(async move { browser.start_reaper() });
            // Scheduled tasks run from now on (also while Oxide is in the tray); runs missed
            // while it was closed are handled first, as each task says.
            tauri::async_runtime::spawn(async move { scheduler.start() });

            let handle = app.handle().clone();
            desktop::apply_settings(&handle, &settings.desktop);
            desktop::tray::build(&handle)?;
            desktop::quick::create(&handle)?;
            setup_deep_links(&handle);
            if !start_hidden {
                desktop::show_main(&handle);
            }
            tracing::info!("{} {} started", oxide_core::APP_NAME, oxide_core::version());
            Ok(())
        })
        .build(tauri::generate_context!())?;

    app.run(|handle, event| match event {
        tauri::RunEvent::Exit => {
            // Stop MCP servers cleanly. On Windows their process trees also end with Oxide
            // (job objects) if this is cut short.
            if let Some(state) = handle.try_state::<state::AppState>() {
                let mcp = state.mcp.clone();
                tauri::async_runtime::block_on(mcp.shutdown());
                // Sandboxes stop too; their files stay. Chats' browsers close.
                let sandboxes = state.sandboxes.clone();
                let browser = state.browser.clone();
                let chrome = state.chrome.clone();
                tauri::async_runtime::block_on(async move {
                    chrome.shutdown().await;
                    let _ = tokio::time::timeout(
                        std::time::Duration::from_secs(15),
                        futures_util::future::join(sandboxes.shutdown(), browser.shutdown()),
                    )
                    .await;
                });
            }
        }
        // Clicking the Dock icon brings the hidden window back.
        #[cfg(target_os = "macos")]
        tauri::RunEvent::Reopen { .. } => desktop::show_main(handle),
        _ => {}
    });

    Ok(())
}

